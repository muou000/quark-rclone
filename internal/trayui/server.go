package trayui

import (
	"context"
	"crypto/subtle"
	"embed"
	"encoding/json"
	"html/template"
	"net/http"
	"strings"

	"github.com/muou000/quark-rclone/internal/redact"
)

//go:embed panel.html
var panelFS embed.FS

// panelTokenHeader carries the panel's one-time access token on every state
// changing request. The panel binds the loopback only, so the token's job is
// not secrecy but isolation: another local process cannot drive the user's
// mount by blind POSTing without knowing the panel URL (ADR 0012 — the
// boundary against a hostile local process is the user session itself, the
// same argument as ADR 0009's loopback endpoint).
const panelTokenHeader = "X-Panel-Token"

// Hooks are the tray-shell capabilities the panel exposes, injected so this
// package never touches the registry or the upgrade layout itself (issue
// #25). All fields optional; a nil hook answers honestly.
type Hooks struct {
	// AutostartEnabled reports the logon-autostart state.
	AutostartEnabled func() bool
	// Autostart enables or removes the logon-autostart entry.
	Autostart func(enabled bool) error
	// StagedVersion reports the upgrade waiting in staging, "" when none.
	StagedVersion func() string
	// Upgrade applies the staged upgrade: the caller stops the mount first
	// and restarts it afterwards (ADR 0006's order).
	Upgrade func(ctx context.Context) error
}

// Server serves the tray's local panel: the embedded page, the panel data
// document, the wizard endpoints and the log export.
type Server struct {
	mgr   *Manager
	token string
	tpl   *template.Template
	hooks Hooks
}

// NewServer wires the panel server. The token is generated by the caller per
// process; the page template is parsed once.
func NewServer(mgr *Manager, token string) *Server {
	raw, err := panelFS.ReadFile("panel.html")
	if err != nil {
		panic("trayui: embedded panel.html missing: " + err.Error())
	}
	tpl := template.Must(template.New("panel").Parse(string(raw)))
	return &Server{mgr: mgr, token: token, tpl: tpl}
}

// WithHooks attaches the tray-shell capability hooks.
func (s *Server) WithHooks(h Hooks) *Server {
	s.hooks = h
	return s
}

// Handler returns the panel's HTTP surface. It never binds anything itself;
// the caller listens on a loopback address only (ADR 0012).
func (s *Server) Handler() http.Handler {
	mux := http.NewServeMux()
	mux.HandleFunc("GET /", s.servePanel)
	mux.HandleFunc("GET /api/panel", s.servePanelData)
	mux.HandleFunc("GET /api/log", s.serveLogExport)
	mux.HandleFunc("POST /api/validate", s.guard(s.serveValidate))
	mux.HandleFunc("POST /api/apply", s.guard(s.serveApply))
	mux.HandleFunc("POST /api/reauth", s.guard(s.serveReauth))
	mux.HandleFunc("POST /api/recheck", s.guard(s.serveRecheck))
	mux.HandleFunc("POST /api/autostart", s.guard(s.serveAutostart))
	mux.HandleFunc("POST /api/upgrade", s.guard(s.serveUpgrade))
	return mux
}

// guard rejects state-changing requests that do not carry the panel token.
func (s *Server) guard(next http.HandlerFunc) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		got := r.Header.Get(panelTokenHeader)
		if got == "" || subtle.ConstantTimeCompare([]byte(got), []byte(s.token)) != 1 {
			http.Error(w, "missing or invalid panel token", http.StatusUnauthorized)
			return
		}
		next(w, r)
	}
}

// servePanel renders the embedded page with the process's token baked in.
func (s *Server) servePanel(w http.ResponseWriter, r *http.Request) {
	if r.URL.Path != "/" {
		http.NotFound(w, r)
		return
	}
	w.Header().Set("Content-Type", "text/html; charset=utf-8")
	_ = s.tpl.Execute(w, s.token)
}

// servePanelData answers with the whole main-panel document, enriched with
// the shell hooks' view (autostart state, staged upgrade).
func (s *Server) servePanelData(w http.ResponseWriter, r *http.Request) {
	data := s.mgr.Panel()
	if s.hooks.AutostartEnabled != nil {
		data.Autostart = s.hooks.AutostartEnabled()
	}
	if s.hooks.StagedVersion != nil {
		data.UpgradeVersion = s.hooks.StagedVersion()
	}
	writeJSON(w, data)
}

// serveLogExport streams the redacted event log as a text file (AC 4).
func (s *Server) serveLogExport(w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Content-Type", "text/plain; charset=utf-8")
	w.Header().Set("Content-Disposition", `attachment; filename="quark-tray-log.txt"`)
	_, _ = w.Write([]byte(s.mgr.log.Export()))
}

// wizardRequest is the JSON body of /api/validate, /api/apply and
// /api/reauth. Cookie is always the candidate the user pasted — it never
// travels anywhere but into validation, and never comes back out.
type wizardRequest struct {
	Cookie   string `json:"cookie"`
	Letter   string `json:"letter"`
	RootFID  string `json:"root_fid"`
	RootPath string `json:"root_path"`
}

// serveValidate runs the wizard's first step: validate the candidate and —
// only on success — list the root directories for the choice step. The
// effective cookie is deliberately not echoed back to the page.
func (s *Server) serveValidate(w http.ResponseWriter, r *http.Request) {
	req, ok := decodeWizard(w, r)
	if !ok {
		return
	}
	if strings.TrimSpace(req.Cookie) == "" {
		writeJSON(w, map[string]any{"ok": false, "error": "请先粘贴 Cookie"})
		return
	}
	effective, err := s.mgr.src.Validate(r.Context(), req.Cookie)
	if err != nil {
		writeJSON(w, map[string]any{"ok": false, "error": redact.Error(err)})
		return
	}
	dirs, err := s.mgr.src.ListDirs(r.Context(), effective)
	if err != nil {
		// The login is good even if the listing failed; the wizard degrades
		// to a free-form FID field instead of blocking.
		writeJSON(w, map[string]any{"ok": true, "dirs": []RootDir{}, "list_error": redact.Error(err)})
		return
	}
	writeJSON(w, map[string]any{"ok": true, "dirs": dirs})
}

// serveApply runs the full first-run configuration: validate, persist
// credential, save root/drive choices, restart. Validation failure leaves
// every durable store untouched (AC 2).
func (s *Server) serveApply(w http.ResponseWriter, r *http.Request) {
	req, ok := decodeWizard(w, r)
	if !ok {
		return
	}
	err := s.mgr.Apply(r.Context(), req.Cookie, MountOptions{
		Letter:   req.Letter,
		RootFID:  req.RootFID,
		RootPath: req.RootPath,
	})
	applyResult(w, err)
}

// serveReauth is the NeedsReauth path (AC 3): validate the new cookie,
// persist it, restart — with no options touched, so root, drive letter,
// profile and dirty cache survive as they are.
func (s *Server) serveReauth(w http.ResponseWriter, r *http.Request) {
	req, ok := decodeWizard(w, r)
	if !ok {
		return
	}
	err := s.mgr.Apply(r.Context(), req.Cookie, MountOptions{})
	applyResult(w, err)
}

// serveRecheck is the tray's recovery action (ADR 0004 重新检查): re-run the
// mount from the stored credential — preflight, readiness and drive probe —
// without any wizard step. The lifecycle work is detached from the HTTP
// request: a client that gives up must not cancel a restart half-done.
func (s *Server) serveRecheck(w http.ResponseWriter, r *http.Request) {
	ctx := context.WithoutCancel(r.Context())
	if err := s.mgr.Recheck(ctx); err != nil {
		writeJSON(w, map[string]any{"ok": false, "error": err.Error()})
		return
	}
	writeJSON(w, map[string]any{"ok": true})
}

// autostartRequest is the body of /api/autostart.
type autostartRequest struct {
	Enabled bool `json:"enabled"`
}

// serveAutostart toggles the current-user logon autostart entry (issue #25,
// ADR 0004): current user only, no elevation, no service.
func (s *Server) serveAutostart(w http.ResponseWriter, r *http.Request) {
	if s.hooks.Autostart == nil {
		writeJSON(w, map[string]any{"ok": false, "error": "此构建不支持自启动"})
		return
	}
	var req autostartRequest
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		http.Error(w, "invalid JSON body", http.StatusBadRequest)
		return
	}
	if err := s.hooks.Autostart(req.Enabled); err != nil {
		writeJSON(w, map[string]any{"ok": false, "error": err.Error()})
		return
	}
	writeJSON(w, map[string]any{"ok": true, "enabled": req.Enabled})
}

// serveUpgrade applies the staged upgrade (issue #25, ADR 0006): the hook
// stops the mount, swaps the payload, self-checks and restarts — rolling back
// on failure. The swap must run to completion or roll back even if the client
// disconnects, so the work is detached from the request context.
func (s *Server) serveUpgrade(w http.ResponseWriter, r *http.Request) {
	if s.hooks.Upgrade == nil {
		writeJSON(w, map[string]any{"ok": false, "error": "此构建不支持在线升级"})
		return
	}
	ctx := context.WithoutCancel(r.Context())
	if err := s.hooks.Upgrade(ctx); err != nil {
		writeJSON(w, map[string]any{"ok": false, "error": err.Error()})
		return
	}
	writeJSON(w, map[string]any{"ok": true})
}

// applyResult maps an Apply outcome onto the panel's answer. Validation and
// configuration errors are the wizard's business (200 + ok:false), so the
// page can show the Chinese remedy; only transport-level surprises are 500s.
func applyResult(w http.ResponseWriter, err error) {
	if err != nil {
		writeJSON(w, map[string]any{"ok": false, "error": err.Error()})
		return
	}
	writeJSON(w, map[string]any{"ok": true})
}

// decodeWizard parses the JSON body, answering 400 on malformed input.
func decodeWizard(w http.ResponseWriter, r *http.Request) (wizardRequest, bool) {
	var req wizardRequest
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		http.Error(w, "invalid JSON body", http.StatusBadRequest)
		return req, false
	}
	return req, true
}

// writeJSON renders one JSON answer; failures are transport noise.
func writeJSON(w http.ResponseWriter, v any) {
	data, err := json.Marshal(v)
	if err != nil {
		http.Error(w, "encoding failed", http.StatusInternalServerError)
		return
	}
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	_, _ = w.Write(data)
}
